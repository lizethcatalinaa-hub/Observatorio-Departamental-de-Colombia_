@st.cache_data(show_spinner="Cargando mapa de Colombia...")
def _cargar_geojson_departamentos():
    urls = [
        "https://raw.githubusercontent.com/caticoa3/colombia_mapa/master/co_2018_MGN_DPTO_POLITICO.geojson",
        "https://raw.githubusercontent.com/santiblanko/colombia.geojson/master/depto.json",
    ]
    geo = None
    for url in urls:
        try:
            r = requests.get(url, timeout=90)
            r.raise_for_status()
            geo = r.json()
            if geo.get("type") == "FeatureCollection" and geo.get("features"):
                break
        except Exception:
            geo = None
    if not geo or not geo.get("features"):
        return {"type": "FeatureCollection", "features": []}

    features_ok = []
    for feat in geo["features"]:
        props = feat.get("properties") or {}
        raw = (props.get("DPTO_CNMBR") or props.get("NOMBRE_DPT") or props.get("name") or
               props.get("NOMBRE") or props.get("dpto_cnmbr") or "")
        nombre = normalizar_departamento(str(raw))
        if not nombre:
            clave = quitar_tildes(str(raw))
            if "bogota" in clave:
                nombre = "Bogotá D.C."
            elif "san andres" in clave or "archipielago" in clave:
                nombre = "San Andrés y Providencia"
            elif "quindio" in clave:
                nombre = "Quindío"
            else:
                continue
        if nombre not in DEPARTAMENTOS_CANONICOS.values():
            continue
        new_props = dict(props)
        new_props["name"] = nombre
        features_ok.append({"type": "Feature", "id": nombre, "properties": new_props, "geometry": feat["geometry"]})
    return {"type": "FeatureCollection", "features": features_ok}

