def deep_learning_lstm(df, depto, indicador, epochs=25, lookback=3):
    if not HAS_TF:
        return "TensorFlow no disponible.", go.Figure()
    serie = get_series(df, depto, indicador)
    if len(serie) < int(lookback) + 8:
        return f"Serie corta ({len(serie)} puntos).", go.Figure()
    lb = int(lookback)
    sc = MinMaxScaler()
    scaled = sc.fit_transform(serie["valor"].values.astype(float).reshape(-1, 1)).flatten()
    X, y = [], []
    for i in range(lb, len(scaled)):
        X.append(scaled[i - lb:i])
        y.append(scaled[i])
    X, y = np.array(X), np.array(y)
    X = X.reshape(X.shape[0], X.shape[1], 1)
    sp = int(len(X) * 0.75)
    model = Sequential([
        Input(shape=(lb, 1)), LSTM(32, return_sequences=True), Dropout(0.2),
        LSTM(16), Dropout(0.2), Dense(1)])
    model.compile(optimizer="adam", loss="mse")
    model.fit(X[:sp], y[:sp], epochs=int(epochs), batch_size=4, validation_split=0.15,
              callbacks=[EarlyStopping(patience=5, restore_best_weights=True)], verbose=0)
    pred = sc.inverse_transform(model.predict(X[sp:], verbose=0).reshape(-1, 1)).flatten()
    real = sc.inverse_transform(y[sp:].reshape(-1, 1)).flatten()
    rmse = float(np.sqrt(mean_squared_error(real, pred)))
    last = scaled[-lb:].tolist()
    fut = []
    for _ in range(5):
        p = model.predict(np.array(last[-lb:]).reshape(1, lb, 1), verbose=0)[0, 0]
        fut.append(p)
        last.append(p)
    fut = sc.inverse_transform(np.array(fut).reshape(-1, 1)).flatten()
    pred_vals = [round(float(x), 2) for x in fut]
    anios_f = list(range(int(serie["anio"].max()) + 1, int(serie["anio"].max()) + 6))
    tabla_pred = pd.DataFrame({"Año": anios_f, "Predicción": pred_vals})
    texto = interp_lstm(depto, indicador, rmse, tabla_pred, len(serie), lb)
    fig = go.Figure()
    fig.add_trace(go.Scatter(x=serie["anio"], y=[float(v) for v in serie["valor"]], mode="lines+markers", name="Histórico"))
    fig.add_trace(go.Scatter(x=serie["anio"].values[-len(real):], y=[float(v) for v in pred], mode="lines+markers", name="Prueba"))
    fig.add_trace(go.Scatter(x=anios_f, y=pred_vals, mode="lines+markers", name="Pronóstico", line=dict(dash="dash")))
    fig.update_layout(title=f"LSTM · {depto} · {indicador}", template="plotly_white", height=420)
    return texto, fig

def prediccion_y_simulacion(panel, target, features, anio_min, anio_max, shock_var, shock_pct, horizon=5):
    features = [f for f in (features or []) if f in VARS_ML and f != target]
    if target not in VARS_ML or len(features) < 1:
        return "Elige variables válidas.", go.Figure(), go.Figure()
    d = panel[(panel["anio"] >= anio_min) & (panel["anio"] <= anio_max)].dropna(subset=[target] + features)
    if len(d) < 25:
        return "Muestra insuficiente.", go.Figure(), go.Figure()
    model = GradientBoostingRegressor(n_estimators=80, max_depth=4, random_state=42)
    model.fit(d[features], d[target])
    last = d.sort_values("anio").groupby("anio")[features + [target]].mean().iloc[-1]
    base, cur = [], last[features].copy()
    for _ in range(int(horizon)):
        base.append(model.predict(cur.values.reshape(1, -1))[0])
        cur = cur * 1.01
    sh = last[features].copy()
    if shock_var in sh.index:
        sh[shock_var] *= (1 + float(shock_pct) / 100)
    scn, cur = [], sh.copy()
    for _ in range(int(horizon)):
        scn.append(model.predict(cur.values.reshape(1, -1))[0])
        cur = cur * 1.01
    anios = list(range(int(d["anio"].max()) + 1, int(d["anio"].max()) + int(horizon) + 1))
    dif = np.array(scn) - np.array(base)
    tab = pd.DataFrame({"Año": anios, "Escenario base": np.round(base, 2),
                        "Con shock": np.round(scn, 2), "Diferencia": np.round(dif, 2)})
    texto = interp_simulacion(target, features, shock_var, shock_pct, tab, float(dif.mean()))
    fig = go.Figure()
    fig.add_scatter(x=anios, y=base, mode="lines+markers", name="Base")
    fig.add_scatter(x=anios, y=scn, mode="lines+markers", name="Con shock", line=dict(dash="dash"))
    fig.update_layout(template="plotly_white")
    imp = pd.Series(model.feature_importances_, index=features).sort_values()
    figi = px.bar(x=imp.values, y=imp.index, orientation="h", template="plotly_white")
    return texto, fig, figi

def interpretabilidad(panel, target, features, anio_min, anio_max):
    features = [f for f in (features or []) if f in VARS_ML and f != target]
    if target not in VARS_ML or not features:
        return "Elige variables válidas.", go.Figure()
    d = panel[(panel["anio"] >= anio_min) & (panel["anio"] <= anio_max)].dropna(subset=[target] + features)
    if len(d) < 20:
        return "Muestra insuficiente.", go.Figure()
    m = RandomForestRegressor(n_estimators=100, max_depth=5, random_state=42)
    m.fit(d[features], d[target])
    perm = permutation_importance(m, d[features], d[target], n_repeats=10, random_state=42)
    imp = pd.DataFrame({"Variable": features, "Importancia": perm.importances_mean, "Desviación": perm.importances_std})
    fig = go.Figure(go.Bar(x=imp["Importancia"], y=imp["Variable"], orientation="h",
                           error_x=dict(type="data", array=imp["Desviación"])))
    fig.update_layout(template="plotly_white", height=420)
    return interp_importancia(target, features, imp), fig

