def tabla_es(df):
    if df is None or getattr(df, "empty", True):
        return pd.DataFrame(columns=["Departamento", "Año", "Valor", "Indicador", "Fuente"])
    out = df.copy().reset_index(drop=True)
    ren = {"departamento": "Departamento", "anio": "Año", "valor": "Valor",
           "indicador": "Indicador", "fuente": "Fuente"}
    out = out.rename(columns={k: v for k, v in ren.items() if k in out.columns})
    nuevas = [f"Columna_{c}" if isinstance(c, (int, np.integer, float, np.floating)) or str(c).isdigit() else str(c)
              for c in out.columns]
    out.columns = nuevas
    orden = [c for c in ["Departamento", "Año", "Valor", "Indicador", "Fuente"] if c in out.columns]
    resto = [c for c in out.columns if c not in orden]
    return out[orden + resto]

