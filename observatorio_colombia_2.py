        if abs(delta) < 1e-9:
            trend = "En el período la serie se ve **estable** (casi no cambió)."
        elif delta > 0:
            trend = f"La serie **subió** aproximadamente **{delta:.2f}** puntos entre el primer y el último año disponible."
        else:
            trend = f"La serie **bajó** aproximadamente **{abs(delta):.2f}** puntos entre el primer y el último año disponible."
        if abs(by.iloc[0]) > 1e-9:
            pct = 100 * delta / abs(by.iloc[0])
            trend += f" Eso equivale a un cambio relativo de alrededor de **{pct:+.1f}%**."
