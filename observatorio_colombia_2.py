def mineria_clustering(panel, anio_ref, n_clusters=4, metodo="KMeans"):
    d = panel[panel["anio"] == int(anio_ref)].copy()
    cols = [c for c in VARS_ML if c in d.columns and d[c].notna().sum() > 5]
    if len(cols) < 2 or len(d) < max(int(n_clusters), 3):
        return "Datos insuficientes.", go.Figure(), go.Figure()
    X = d[cols].fillna(d[cols].median())
    Xs = StandardScaler().fit_transform(X)
    k = int(n_clusters)
    if metodo == "KMeans":
        labels = KMeans(n_clusters=k, random_state=42, n_init=10).fit_predict(Xs)
    elif metodo == "Hierarchical":
        labels = AgglomerativeClustering(n_clusters=k).fit_predict(Xs)
    else:
        labels = DBSCAN(eps=1.2, min_samples=2).fit_predict(Xs)
        k = len(set(labels)) - (1 if -1 in labels else 0)
    sil = float(silhouette_score(Xs, labels)) if k > 1 and -1 not in set(labels) else 0.0
    d["cluster"] = labels
    texto = interp_clustering(metodo, k, sil, cols)
    texto += "\n\n" + d.groupby("cluster")[cols].mean().round(2).to_markdown()
    coords = PCA(2).fit_transform(Xs)
    d["PC1"], d["PC2"] = coords[:, 0], coords[:, 1]
    fig1 = px.scatter(d, x="PC1", y="PC2", color="cluster", text="departamento", template="plotly_white")
    fig1.update_traces(textposition="top center", textfont_size=9)
    mel = d.groupby("cluster")[cols].mean().reset_index().melt("cluster")
    fig2 = px.bar(mel, x="variable", y="value", color="cluster", barmode="group", template="plotly_white")
    return texto, fig1, fig2

def analisis_pca(panel, anio_min, anio_max, n_comp=3):
    d = panel[(panel["anio"] >= anio_min) & (panel["anio"] <= anio_max)].copy()
    cols = [c for c in VARS_ML if c in d.columns and d[c].notna().sum() > 10]
