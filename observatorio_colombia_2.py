def normalizar_departamento(nombre):
    if pd.isna(nombre) or nombre is None:
        return None
    t = re.sub(r"^\d{1,5}[\s\-_]*", "", str(nombre).strip()).strip()
    if not t or re.match(r"^\d+$", t):
        return None
    clave = quitar_tildes(t)
    if clave in DEPARTAMENTOS_CANONICOS:
        return DEPARTAMENTOS_CANONICOS[clave]
    for k, v in DEPARTAMENTOS_CANONICOS.items():
        if clave == k or clave.startswith(k + " "):
            return v
    return t.title() if len(clave) >= 3 else None

